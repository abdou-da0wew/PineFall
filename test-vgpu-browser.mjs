import { artifact, testUrl, projectRoot } from './scripts/test-support.mjs';
import { chromium, expect } from '@playwright/test';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-webgpu','--enable-features=Vulkan','--use-angle=vulkan','--use-vulkan=swiftshader','--use-webgpu-adapter=swiftshader','--disable-vulkan-surface']});
const page=await browser.newPage({viewport:{width:1200,height:800}});let errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto(testUrl('/?renderer=vgpu'));
await page.getByRole('button',{name:'START YOUR SHIFT'}).waitFor();
await page.locator('button[title="Renderer settings"]').click();
await page.waitForFunction(()=>document.querySelector('.renderer-status strong')?.textContent.includes('vgpu 0.6.0'),{},{timeout:25000});
console.log('status',await page.locator('.renderer-status').innerText());console.log('note',await page.locator('.renderer-note').innerText());console.log('errors',errors);
await page.screenshot({path:artifact('vgpu-browser-settings.png')});
await page.getByRole('button',{name:'BACK TO THE ROAD'}).click();
await page.getByRole('button',{name:'START YOUR SHIFT'}).click();await page.keyboard.press('e');await page.waitForTimeout(500);
await expect(page.getByText('▣ Telescope lens')).toBeVisible();
console.log('cargo',await page.getByText('▣ Telescope lens').count());
await page.keyboard.down('w');await page.waitForTimeout(1500);await page.keyboard.up('w');console.log('speed',await page.locator('.speed').innerText());
await page.screenshot({path:artifact('vgpu-browser-game.png')});
await browser.close();
if(errors.length)process.exitCode=1;
